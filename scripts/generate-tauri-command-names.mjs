import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rustSourcePath = resolve(root, "src-tauri/src/lib.rs");
const outputPath = resolve(root, "src/generated/tauri-command-names.ts");
const handlerMarker = "tauri::generate_handler![";

function extractCommandNames(source) {
  const handlerStart = source.indexOf(handlerMarker);
  if (handlerStart === -1) {
    throw new Error(`Could not find ${handlerMarker} in ${rustSourcePath}`);
  }

  const listStart = handlerStart + handlerMarker.length;
  const listEnd = source.indexOf("])", listStart);
  if (listEnd === -1) {
    throw new Error(`Could not find the end of ${handlerMarker} in ${rustSourcePath}`);
  }

  const commands = source
    .slice(listStart, listEnd)
    .replace(/\/\/.*$/gm, "")
    .split(",")
    .map((command) => command.trim())
    .filter(Boolean);

  for (const command of commands) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(command)) {
      throw new Error(`Unsupported Tauri command entry: ${command}`);
    }
  }

  if (new Set(commands).size !== commands.length) {
    throw new Error("The Tauri handler contains duplicate command registrations");
  }

  return commands;
}

function render(commandNames) {
  return `// This file is generated by scripts/generate-tauri-command-names.mjs.
// Do not edit it by hand; src-tauri/src/lib.rs is the command-name authority.

export const tauriCommandNames = [
${commandNames.map((name) => `  "${name}",`).join("\n")}
] as const;

export type TauriCommandName = (typeof tauriCommandNames)[number];
`;
}

const expected = render(extractCommandNames(readFileSync(rustSourcePath, "utf8")));
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  let actual = "";
  try {
    actual = readFileSync(outputPath, "utf8");
  } catch {
    // Missing generated output is reported as the same stale-contract failure.
  }

  if (actual !== expected) {
    process.stderr.write(
      "Generated Tauri command names are stale. Run `pnpm contract:generate` and commit the result."
    );
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, expected);
}
